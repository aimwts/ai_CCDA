-- Run this in the Supabase SQL Editor before starting the backend.
CREATE TABLE IF NOT EXISTS public.sensor_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sensor text NOT NULL,
  metric text NOT NULL DEFAULT 'value',
  value double precision NOT NULL,
  timestamp timestamptz NOT NULL DEFAULT now()
);

-- Upgrade the earlier three-column schema without removing existing data.
ALTER TABLE public.sensor_history
  ADD COLUMN IF NOT EXISTS metric text NOT NULL DEFAULT 'value';

CREATE INDEX IF NOT EXISTS sensor_history_sensor_timestamp_idx
  ON public.sensor_history (sensor, timestamp DESC);

-- The app accesses Postgres from its backend, never from the browser.
-- RLS prevents direct Data API access unless an explicit policy is added.
ALTER TABLE public.sensor_history ENABLE ROW LEVEL SECURITY;
